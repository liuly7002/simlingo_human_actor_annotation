#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""Generate ``lg_predictions.jsonl`` for human-vs-LG actor evaluation.

The script reads the human-annotation manifest and, for every listed sample,
locates the LG label generated by ``lg_waypoint_planner_project``. It extracts:

* ``selected_actor_id`` from ``causal_analysis.causal_object.id`` only when
  ``causal_analysis.has_causal_object`` is true;
* ordered analysis candidates from
  ``causal_analysis.object_tests[*].actor.id``.

The output can be passed directly to ``evaluate_annotations.py --predictions``.
"""

from __future__ import annotations

import argparse
import gzip
import json
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

import yaml


DEFAULT_LG_FOLDERS: Tuple[str, ...] = (
    "language_grounded_waypoints",
    "language_grounded_waypoints_v2",
    "lg_waypoint_labels",
    "lg_labels",
    "lg_waypoints",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="根据人工标注 manifest 自动生成 LG actor 预测文件"
    )
    parser.add_argument("--config", required=True, help="人工标注项目的 config.yaml")
    parser.add_argument(
        "--manifest",
        default=None,
        help="可选：覆盖 config.yaml 中的 dataset.manifest_path",
    )
    parser.add_argument(
        "--output",
        default=None,
        help=(
            "输出 lg_predictions.jsonl；默认写入 "
            "<dataset.work_dir>/evaluation/lg_predictions.jsonl"
        ),
    )
    parser.add_argument(
        "--summary-output",
        default=None,
        help="可选：生成过程统计 JSON；默认与输出 JSONL 同目录",
    )
    parser.add_argument(
        "--lg-folder",
        action="append",
        default=[],
        help=(
            "LG 标签相对于每条 route 的目录名。可重复传入；不填写时先尝试常见目录，"
            "再扫描 route 的一级子目录。"
        ),
    )
    parser.add_argument(
        "--recursive-search",
        action="store_true",
        help="一级目录未找到时，递归搜索同帧 JSON/JSON.GZ（数据很大时会较慢）",
    )
    parser.add_argument(
        "--fail-on-missing",
        action="store_true",
        help="存在缺失或无法解析的 LG 标签时以非零状态退出",
    )
    return parser.parse_args()


def _resolve_path(base_dir: Path, value: Any) -> Path:
    path = Path(str(value)).expanduser()
    if not path.is_absolute():
        path = (base_dir / path).resolve()
    return path


def _load_project_paths(config_path: Path, manifest_override: Optional[str]) -> Tuple[Path, Path, Path]:
    with config_path.open("r", encoding="utf-8") as handle:
        raw = yaml.safe_load(handle) or {}

    dataset = raw.get("dataset", {}) or {}
    if "dataset_root" not in dataset:
        raise ValueError("配置文件缺少 dataset.dataset_root")

    base_dir = config_path.parent
    dataset_root = _resolve_path(base_dir, dataset["dataset_root"])
    work_dir = _resolve_path(base_dir, dataset.get("work_dir", "./annotation_workspace"))

    if manifest_override:
        manifest_path = _resolve_path(Path.cwd(), manifest_override)
    else:
        manifest_value = dataset.get("manifest_path", str(work_dir / "manifest.jsonl"))
        manifest_path = _resolve_path(base_dir, manifest_value)

    return dataset_root, work_dir, manifest_path


def _read_jsonl(path: Path) -> List[Dict[str, Any]]:
    records: List[Dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            stripped = line.strip()
            if not stripped:
                continue
            try:
                item = json.loads(stripped)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number} 不是合法 JSON：{exc}") from exc
            if not isinstance(item, dict):
                raise ValueError(f"{path}:{line_number} 必须是 JSON 对象")
            records.append(item)
    return records


def _load_json_auto(path: Path) -> Any:
    if path.name.endswith(".json.gz"):
        with gzip.open(str(path), "rt", encoding="utf-8") as handle:
            return json.load(handle)
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def _is_lg_label(data: Any) -> bool:
    if not isinstance(data, dict):
        return False
    causal = data.get("causal_analysis")
    if not isinstance(causal, dict):
        return False
    return bool(
        "has_causal_object" in causal
        or "causal_object" in causal
        or "object_tests" in causal
    )


def _actor_id(value: Any) -> Optional[str]:
    if value is None:
        return None
    if isinstance(value, dict):
        for key in ("id", "actor_id", "selected_actor_id", "critical_actor_id"):
            if value.get(key) is not None:
                return str(value[key])
        return None
    if isinstance(value, (str, int)):
        return str(value)
    return None


def _extract_prediction(label: Dict[str, Any]) -> Dict[str, Any]:
    causal = label.get("causal_analysis", {}) or {}
    has_causal_object = bool(causal.get("has_causal_object", False))
    primary_actor_id = (
        _actor_id(causal.get("causal_object")) if has_causal_object else None
    )

    candidate_actor_ids: List[str] = []
    candidate_details: List[Dict[str, Any]] = []
    object_tests = causal.get("object_tests", []) or []
    if isinstance(object_tests, list):
        for rank, test in enumerate(object_tests, start=1):
            if not isinstance(test, dict):
                continue
            actor = test.get("actor", {}) or {}
            actor_id = _actor_id(actor)
            if actor_id is None or actor_id in candidate_actor_ids:
                continue
            candidate_actor_ids.append(actor_id)
            candidate_details.append(
                {
                    "rank": rank,
                    "actor_id": actor_id,
                    "counterfactual_valid": bool(test.get("counterfactual_valid", False)),
                    "causal_accepted": bool(test.get("causal_accepted", False)),
                    "causal_score": test.get("causal_score"),
                    "final_causal_score": test.get("final_causal_score"),
                }
            )

    return {
        "selected_actor_id": primary_actor_id,
        "candidate_actor_ids": candidate_actor_ids,
        "candidate_details": candidate_details,
        "has_causal_object": has_causal_object,
        "causal_score": causal.get("causal_score"),
        "preliminary_causal_score": causal.get("preliminary_causal_score"),
        "final_causal_score": causal.get("final_causal_score"),
        "final_revalidation_passed": causal.get("final_revalidation_passed"),
        "causal_acceptance_reason": causal.get("causal_acceptance_reason"),
    }


def _resolve_route_dir(sample: Dict[str, Any], dataset_root: Path) -> Optional[Path]:
    route_value = sample.get("route_dir")
    if route_value:
        route_path = Path(str(route_value)).expanduser()
        if not route_path.is_absolute():
            route_path = dataset_root / route_path
        return route_path.resolve()

    boxes_value = sample.get("boxes_path")
    if boxes_value:
        boxes_path = Path(str(boxes_value)).expanduser()
        if not boxes_path.is_absolute():
            boxes_path = dataset_root / boxes_path
        # Expected layout: <route>/boxes/<frame>.json.gz
        return boxes_path.resolve().parent.parent
    return None


def _label_filenames(frame_stem: str) -> Tuple[str, str]:
    return f"{frame_stem}.json.gz", f"{frame_stem}.json"


def _folder_priority(folder: Path, explicit_names: Sequence[str]) -> Tuple[int, str]:
    name = folder.name
    if name in explicit_names:
        return (0, name)
    if name in DEFAULT_LG_FOLDERS:
        return (1, name)
    lowered = name.lower()
    if "language_grounded_waypoints" in lowered and "debug" not in lowered:
        return (2, name)
    if "grounded" in lowered and "waypoint" in lowered and "debug" not in lowered:
        return (3, name)
    if "full_debug" in lowered or "debug" in lowered:
        return (9, name)
    return (5, name)


def _candidate_label_paths(
    route_dir: Path,
    frame_stem: str,
    explicit_folders: Sequence[str],
    cached_folder: Optional[Path],
    recursive_search: bool,
) -> Iterable[Path]:
    filenames = _label_filenames(frame_stem)
    emitted = set()

    def emit(path: Path) -> Iterable[Path]:
        resolved = path.resolve()
        key = str(resolved)
        if key not in emitted and resolved.is_file():
            emitted.add(key)
            yield resolved

    if cached_folder is not None:
        for filename in filenames:
            yield from emit(cached_folder / filename)

    folder_names: List[str] = []
    for name in list(explicit_folders) + list(DEFAULT_LG_FOLDERS):
        if name and name not in folder_names:
            folder_names.append(name)
    for folder_name in folder_names:
        folder = Path(folder_name)
        if not folder.is_absolute():
            folder = route_dir / folder
        for filename in filenames:
            yield from emit(folder / filename)

    try:
        child_dirs = sorted(
            [path for path in route_dir.iterdir() if path.is_dir()],
            key=lambda path: _folder_priority(path, explicit_folders),
        )
    except OSError:
        child_dirs = []
    for folder in child_dirs:
        for filename in filenames:
            yield from emit(folder / filename)

    if recursive_search:
        for filename in filenames:
            try:
                matches = sorted(route_dir.rglob(filename))
            except OSError:
                matches = []
            for path in matches:
                yield from emit(path)


def _find_lg_label(
    route_dir: Path,
    frame_stem: str,
    explicit_folders: Sequence[str],
    cached_folder: Optional[Path],
    recursive_search: bool,
) -> Tuple[Optional[Path], Optional[Dict[str, Any]], List[str]]:
    errors: List[str] = []
    for path in _candidate_label_paths(
        route_dir=route_dir,
        frame_stem=frame_stem,
        explicit_folders=explicit_folders,
        cached_folder=cached_folder,
        recursive_search=recursive_search,
    ):
        try:
            data = _load_json_auto(path)
        except Exception as exc:  # keep searching other same-frame JSON files
            errors.append(f"{path}: {type(exc).__name__}: {exc}")
            continue
        if _is_lg_label(data):
            return path, data, errors
    return None, None, errors


def _write_jsonl(path: Path, records: Sequence[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")


def main() -> int:
    args = parse_args()
    config_path = Path(args.config).expanduser().resolve()
    dataset_root, work_dir, manifest_path = _load_project_paths(
        config_path, args.manifest
    )
    if not manifest_path.is_file():
        raise FileNotFoundError(f"manifest 不存在：{manifest_path}")

    output_path = (
        Path(args.output).expanduser().resolve()
        if args.output
        else (work_dir / "evaluation" / "lg_predictions.jsonl").resolve()
    )
    summary_path = (
        Path(args.summary_output).expanduser().resolve()
        if args.summary_output
        else output_path.with_name(output_path.stem + "_summary.json")
    )

    samples = _read_jsonl(manifest_path)
    predictions: List[Dict[str, Any]] = []
    missing_labels: List[Dict[str, Any]] = []
    invalid_samples: List[Dict[str, Any]] = []
    parse_warnings: List[Dict[str, Any]] = []
    duplicate_sample_ids: List[str] = []
    seen_sample_ids = set()
    route_folder_cache: Dict[str, Path] = {}
    primary_not_in_candidates: List[str] = []

    for sample in samples:
        sample_id = str(sample.get("sample_id", "")).strip()
        frame_stem = str(sample.get("center_stem", "")).strip()
        route_dir = _resolve_route_dir(sample, dataset_root)

        if not sample_id or not frame_stem or route_dir is None:
            invalid_samples.append(
                {
                    "sample_id": sample_id,
                    "reason": "missing_sample_id_center_stem_or_route_dir",
                }
            )
            continue
        if sample_id in seen_sample_ids:
            duplicate_sample_ids.append(sample_id)
            continue
        seen_sample_ids.add(sample_id)

        route_key = str(route_dir)
        label_path, label, warnings = _find_lg_label(
            route_dir=route_dir,
            frame_stem=frame_stem,
            explicit_folders=args.lg_folder,
            cached_folder=route_folder_cache.get(route_key),
            recursive_search=bool(args.recursive_search),
        )
        if warnings:
            parse_warnings.append({"sample_id": sample_id, "warnings": warnings})
        if label_path is None or label is None:
            missing_labels.append(
                {
                    "sample_id": sample_id,
                    "route_dir": str(route_dir),
                    "center_stem": frame_stem,
                }
            )
            continue

        route_folder_cache[route_key] = label_path.parent
        extracted = _extract_prediction(label)
        primary_actor_id = extracted["selected_actor_id"]
        candidate_actor_ids = extracted["candidate_actor_ids"]
        if primary_actor_id is not None and primary_actor_id not in candidate_actor_ids:
            primary_not_in_candidates.append(sample_id)

        predictions.append(
            {
                "sample_id": sample_id,
                "route_name": sample.get("route_name", ""),
                "center_stem": frame_stem,
                "selected_actor_id": primary_actor_id,
                "candidate_actor_ids": candidate_actor_ids,
                "has_causal_object": extracted["has_causal_object"],
                "causal_score": extracted["causal_score"],
                "preliminary_causal_score": extracted["preliminary_causal_score"],
                "final_causal_score": extracted["final_causal_score"],
                "final_revalidation_passed": extracted["final_revalidation_passed"],
                "causal_acceptance_reason": extracted["causal_acceptance_reason"],
                "candidate_details": extracted["candidate_details"],
                "lg_label_path": str(label_path),
            }
        )

    _write_jsonl(output_path, predictions)

    with_primary = sum(record.get("selected_actor_id") is not None for record in predictions)
    without_primary = len(predictions) - with_primary
    with_candidates = sum(bool(record.get("candidate_actor_ids")) for record in predictions)
    summary = {
        "config_path": str(config_path),
        "dataset_root": str(dataset_root),
        "manifest_path": str(manifest_path),
        "output_path": str(output_path),
        "manifest_samples": len(samples),
        "prediction_records_written": len(predictions),
        "labels_with_primary_causal_actor": with_primary,
        "labels_without_primary_causal_actor": without_primary,
        "labels_with_analysis_candidates": with_candidates,
        "missing_lg_label_count": len(missing_labels),
        "invalid_manifest_sample_count": len(invalid_samples),
        "duplicate_sample_id_count": len(duplicate_sample_ids),
        "primary_not_in_candidate_list_count": len(primary_not_in_candidates),
        "missing_lg_labels": missing_labels,
        "invalid_manifest_samples": invalid_samples,
        "duplicate_sample_ids": duplicate_sample_ids,
        "primary_not_in_candidate_list": primary_not_in_candidates,
        "parse_warnings": parse_warnings,
        "lg_folders_requested": list(args.lg_folder),
        "recursive_search": bool(args.recursive_search),
    }
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    with summary_path.open("w", encoding="utf-8") as handle:
        json.dump(summary, handle, ensure_ascii=False, indent=2)

    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print(f"\nLG predictions：{output_path}")
    print(f"生成统计：{summary_path}")

    has_problem = bool(missing_labels or invalid_samples or duplicate_sample_ids)
    if args.fail_on_missing and has_problem:
        return 2
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as exc:
        print(f"[ERROR] {type(exc).__name__}: {exc}", file=sys.stderr)
        sys.exit(1)
